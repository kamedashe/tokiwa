import type { MetadataRoute } from "next";
import { SITE_URL } from "@/lib/seo";

/**
 * Личные страницы закрываем на всех языках сразу — «*» в начале паттерна
 * ловит и голый путь («/my»), и с языковым префиксом («/uk/my»), поскольку
 * по robots.txt это не анкорится к началу адреса.
 *
 * /backlog НЕ закрыт: с гостевым режимом это витрина главной фичи — считать
 * можно без входа, и запросы «сколько времени займёт посмотреть …» должны
 * приводить именно сюда.
 */
export default function robots(): MetadataRoute.Robots {
  return {
    rules: {
      userAgent: "*",
      allow: "/",
      // Каталог — это 15 тысяч страниц на четырёх языках. Обход без паузы
      // в августе 2026 выбрал месячную квоту базы за несколько дней, так
      // что просим ботов ходить медленнее. Googlebot директиву игнорирует —
      // ему скорость задаётся в Search Console, остальные уважают.
      crawlDelay: 3,
      // Адреса-метки — редиректы для рекламы, в индексе им делать нечего.
      //
      // «*/search?» закрывает смысловой поиск с запросом, но не саму
      // страницу: каждый такой адрес — это поход в модель за вектором, и
      // отдавать их на обход боту незачем. Пустая /search в индексе нужна.
      disallow: [
        "*/search?",
        "/api/",
        "*/my",
        "*/login",
        "*/feedback",
        "*/wrapped",
        "/tt",
        "/yt",
        "/ig",
        "/tg",
      ],
    },
    sitemap: `${SITE_URL}/sitemap.xml`,
  };
}
