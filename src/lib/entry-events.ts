/**
 * Событие «запись списка изменилась» — им обмениваются блоки на странице
 * тайтла.
 *
 * Кнопки статуса и счётчик серий стоят в разных колонках вёрстки, поэтому
 * живут отдельными компонентами со своим состоянием. Пока страница
 * рендерилась на сервере, их синхронизировал общий рендер; теперь страница
 * отдаётся из кэша, а личное подтягивается в браузере — и блоки перестали
 * видеть изменения друг друга. Событие возвращает эту связь, не заводя ради
 * двух компонентов общий провайдер поверх всей страницы.
 */

export const ENTRY_CHANGED = "tokiwa:entry-changed";

export interface EntryChangedDetail {
  titleId: number;
  /** Новое число отмеченных серий. */
  progress: number;
}
