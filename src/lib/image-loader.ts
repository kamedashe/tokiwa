"use client";

/**
 * Свой лоадер вместо оптимизатора Vercel: на бесплатном тарифе квота
 * трансформаций сгорела за два дня (15 тыс. уникальных постеров), и всё,
 * что не успело в кэш, стало отдавать 402 — «некоторые картинки не грузятся».
 *
 * Вместо этого пользуемся тем, что у Shikimori уже лежат готовые размеры:
 * для карточек берём /preview/ (~225px), крупным постерам и баннерам
 * оставляем оригинал. Остальные хосты (AniList, аватары) отдаются как есть —
 * их немного, и они и так адекватного размера.
 */
export default function imageLoader({ src, width }: { src: string; width: number }) {
  if (src.includes("shikimori.io") && src.includes("/original/") && width <= 384) {
    return src.replace("/original/", "/preview/");
  }
  return src;
}
