/**
 * Как вектор выглядит в SQL. Одно место на все скрипты: разъедься здесь тип
 * колонки и тип литерала — Postgres молча сравнит не то с тем.
 */

/**
 * halfvec — тот же вектор, но по два байта на число вместо четырёх. На
 * косинусе разница уходит в шестой знак и тонет в самой модели, а места
 * занимает вдвое меньше.
 *
 * 512 измерений вместо 1024: Voyage обучен матрёшкой, обрезание задумано
 * авторами. Вместе с halfvec вектор весит килобайт вместо четырёх и умещается
 * в самой строке таблицы, не уезжая в TOAST. Ради этого всё и затевалось:
 * на бесплатном Neon база упёрлась в 460 МБ из 512, из которых 162 МБ —
 * вектора в TOAST и 243 МБ — индекс.
 */
export const VECTOR_DIMENSIONS = 512;
export const VECTOR_SQL_TYPE = `halfvec(${VECTOR_DIMENSIONS})`;

/**
 * pgvector принимает вектор строкой '[0.1,0.2,...]'. Шесть знаков после
 * запятой урезают запрос вдвое, а на косинусе при пятистах измерениях разница
 * порядка 1e-6 — она и так тонет в переводе во float16.
 */
export function toVectorLiteral(v: number[]): string {
  return `[${v.map((x) => x.toFixed(6)).join(",")}]`;
}
